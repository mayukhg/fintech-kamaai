const dictionaries: Record<Lang, Record<Key, string>> = { en, hi, mr }

export function t(lang: Lang, key: Key, vars?: Record<string, string>): string {
  let text: string = dictionaries[lang][key] ?? en[key]
  if (!vars) return text
  for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, value)
  return text
}

export function bandLabel(lang: Lang, band: 'A' | 'B' | 'C'): string {
  if (band === 'A') return t(lang, 'stable')
  if (band === 'B') return t(lang, 'partial')
  return t(lang, 'unstable')
}
