import { expect, test } from '@playwright/test'
import { buildPassport, chooseEnglishLoan, consentAndRead, fillOtp } from './helpers'

test('worker shares a passport and the lender sees only the consented fields', async ({ page }) => {
  await buildPassport(page)
  await expect(page.getByText(/26,800/)).toBeVisible()
  await expect(page.getByText(/24,100/)).toBeVisible()
  await expect(page.getByText('6 / 6')).toBeVisible()
  await expect(page.getByText(/Band A/)).toBeVisible()
  await page.getByRole('button', { name: 'Share with lender or landlord' }).click()
  await page.getByRole('checkbox', { name: 'Full account number' }).check()
  await page.getByRole('checkbox', { name: 'Monthly table and sources' }).uncheck()
  await page.getByRole('button', { name: 'Create share link' }).click()
  await expect(page.getByText(/#\/v\/ravi-/)).toBeVisible()
  await page.getByRole('button', { name: 'Preview verifier view' }).click()
  await expect(page.getByRole('heading', { name: 'Kamai Passport' })).toBeVisible()
  await expect(page.getByText(/26,800/)).toBeVisible()
  await expect(page.getByText('0000004521')).toBeVisible()
  await expect(page.getByText('Sep 2026')).toHaveCount(0)
  await expect(page.getByText(/Signature valid/)).toBeVisible()
  await expect(page.getByText(/Swiggy, Rapido/)).toBeVisible()
  await expect(page.getByText(/Self-reported: .*0/)).toBeVisible()
  await expect(page.getByText(/round-trip/)).toBeVisible()
})

test('a hand-tagged payout stays out of verified income', async ({ page }) => {
  await chooseEnglishLoan(page)
  await consentAndRead(page, /SBI/)
  await expect(page.getByText(/Round-trip/)).toBeVisible()
  await expect(page.getByText(/One-off/)).toBeVisible()
  await page.getByRole('button', { name: /Tag unmatched/ }).click()
  await page.getByRole('button', { name: 'Save as self-reported' }).click()
  await expect(page.getByText(/Self-reported/)).toBeVisible()
  await expect(page.getByRole('button', { name: /Tag unmatched/ })).toHaveCount(0)
  await page.getByRole('button', { name: 'Looks right' }).click()
  await expect(page.getByText(/26,800/)).toBeVisible()
  await expect(page.getByText(/3,150/)).toBeVisible()
})

test('a wrong OTP stays on the consent step', async ({ page }) => {
  await chooseEnglishLoan(page)
  await page.getByRole('button', { name: 'Continue' }).click()
  await page.getByRole('button', { name: 'Approve with OTP' }).click()
  await page.getByRole('button', { name: 'Confirm consent' }).click()
  await expect(page.getByRole('alert')).toContainText('6-digit')
  await expect(page).toHaveURL(/#\/otp$/)
  await fillOtp(page, '000000')
  await page.getByRole('button', { name: 'Confirm consent' }).click()
  await expect(page.getByRole('alert')).toContainText('not accepted')
  await expect(page).toHaveURL(/#\/otp$/)
})

test('an account with no platform credits asks for another bank', async ({ page }) => {
  await chooseEnglishLoan(page)
  await consentAndRead(page, /HDFC/)
  await expect(page.getByText('No platform payouts in the last 6 months on this account.')).toBeVisible()
  await page.getByRole('button', { name: 'Choose another account' }).click()
  await expect(page.getByRole('heading', { name: 'Which account gets your payouts?' })).toBeVisible()
})

test('revoking consent closes the share link', async ({ page }) => {
  await buildPassport(page)
  await page.getByRole('button', { name: 'Share with lender or landlord' }).click()
  await page.getByRole('button', { name: 'Create share link' }).click()
  const url = (await page.locator('.linkline').innerText()).trim()
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('button', { name: 'Revoke consent' }).click()
  await page.getByRole('button', { name: 'Confirm revoke' }).click()
  await expect(page.getByRole('status')).toContainText('Consent revoked')
  await page.goto(url)
  await expect(page.getByRole('heading', { name: 'This Passport was revoked by the worker.' })).toBeVisible()
})

test('the passport is still there after a reload', async ({ page }) => {
  await buildPassport(page)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Your Passport' })).toBeVisible()
  await expect(page.getByText(/26,800/)).toBeVisible()
  await expect(page.getByText(/Band A/)).toBeVisible()
})

test('pdf and json downloads use the shared report', async ({ page }) => {
  await buildPassport(page)
  await page.getByRole('button', { name: 'Share with lender or landlord' }).click()
  await page.getByRole('button', { name: 'Create share link' }).click()
  const pdf = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download PDF' }).click()
  expect((await pdf).suggestedFilename()).toBe('kamai-passport.pdf')
  await page.getByRole('button', { name: 'Preview verifier view' }).click()
  const json = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download JSON' }).click()
  expect((await json).suggestedFilename()).toBe('kamai-passport.json')
})
